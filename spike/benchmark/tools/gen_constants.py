#!/usr/bin/env python3
"""Canonical constant generation for the FP vs FX64 spike.

All scaling and rounding is performed with exact rational / integer arithmetic
(fractions.Fraction + int).  Hex-float literals are parsed exactly, no
`long double` is used, and no `double` representation of 2**64 is ever
constructed.

Outputs:
    src/constants.hpp      - consumed by both implementations
    results/constants.md   - the record reproduced in summary.md section 2
"""

import struct
from fractions import Fraction
from pathlib import Path

TWO64 = 1 << 64

# Mathematical initialisation values (exactly representable as double).
X0_HEX = "0x1.123456789abcp-4"
DELTA_HEX = "0x1.6a09e667f3bccp-7"

# `eps` denotes the exact decimal real value.
EPS_LABELS = ["1e-6", "1e-9", "1e-12"]
EPS_EXACT = [Fraction(1, 10 ** 6), Fraction(1, 10 ** 9), Fraction(1, 10 ** 12)]


def round_half_even(fr: Fraction) -> int:
    """round_nearest_even on a non-negative exact rational."""
    assert fr >= 0
    q, r = divmod(fr.numerator, fr.denominator)
    twice = 2 * r
    if twice > fr.denominator:
        q += 1
    elif twice == fr.denominator and (q & 1):
        q += 1
    return q


def dbits(x: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def main() -> None:
    root = Path(__file__).resolve().parent.parent

    x0_d = float.fromhex(X0_HEX)          # exact: hex float parse is exact
    delta_d = float.fromhex(DELTA_HEX)

    X0 = round_half_even(Fraction(x0_d) * TWO64)
    D64 = round_half_even(Fraction(delta_d) * TWO64)

    rows = []
    for label, eps_exact in zip(EPS_LABELS, EPS_EXACT):
        w = round_half_even(eps_exact * TWO64)
        eps_d = float(label)                      # correctly rounded double
        ome_d = 1.0 - eps_d                       # correctly rounded double
        assert 0 < 2 * w < TWO64, (label, w)
        rows.append(dict(label=label, eps_exact=eps_exact, W=w,
                         eps_bits=dbits(eps_d), ome_bits=dbits(ome_d),
                         eps_d=eps_d, ome_d=ome_d))

    assert 0 <= X0 < TWO64
    assert 0 <= D64 < TWO64

    hpp = root / "src" / "constants.hpp"
    with hpp.open("w", newline="\n") as f:
        f.write("// GENERATED by tools/gen_constants.py - do not edit by hand.\n")
        f.write("// Exact integer/rational scaling; no long double, no double 2^64.\n")
        f.write("#pragma once\n#include <cstdint>\n\nnamespace spike {\n\n")
        f.write("inline constexpr int kNumEps = %d;\n" % len(rows))
        f.write('inline constexpr const char* kEpsLabel[%d] = {%s};\n\n'
                % (len(rows), ", ".join('"%s"' % r["label"] for r in rows)))
        f.write("// x0    = %s\n" % X0_HEX)
        f.write("// Delta = %s\n" % DELTA_HEX)
        f.write("inline constexpr uint64_t kX0Bits    = 0x%016xull;\n" % dbits(x0_d))
        f.write("inline constexpr uint64_t kDeltaBits = 0x%016xull;\n\n" % dbits(delta_d))
        f.write("// FX64: fractions of 2^64, round_nearest_even.\n")
        f.write("inline constexpr uint64_t kX0Fx  = 0x%016xull;\n" % X0)
        f.write("inline constexpr uint64_t kD64Fx = 0x%016xull;\n\n" % D64)
        for name, key in (("kWEps", "W"), ("kEpsBits", "eps_bits"),
                          ("kOneMinusEpsBits", "ome_bits")):
            f.write("inline constexpr uint64_t %s[%d] = {\n" % (name, len(rows)))
            for r in rows:
                f.write("    0x%016xull, // %s\n" % (r[key], r["label"]))
            f.write("};\n\n")
        f.write("} // namespace spike\n")

    md = root / "results" / "constants.md"
    with md.open("w", newline="\n") as f:
        f.write("# Canonical Constants\n\n")
        f.write("Generated by `tools/gen_constants.py` using `fractions.Fraction` and\n")
        f.write("arbitrary-precision integers: hex-float parsing is exact, scaling by\n")
        f.write("`2^64` is exact integer/rational, and rounding is explicit\n")
        f.write("round-to-nearest-even. No `long double` is used and no `double`\n")
        f.write("representation of `2^64` is ever constructed.\n\n")
        f.write("Shared by all three eps values:\n\n```text\n")
        f.write("x0                = %s  (= %s)\n" % (X0_HEX, x0_d.hex()))
        f.write("x0_double_bits    = 0x%016x\n" % dbits(x0_d))
        f.write("Delta             = %s  (= %s)\n" % (DELTA_HEX, delta_d.hex()))
        f.write("Delta_double_bits = 0x%016x\n" % dbits(delta_d))
        f.write("X0                = 0x%016x  (%d)\n" % (X0, X0))
        f.write("D64               = 0x%016x  (%d)\n" % (D64, D64))
        f.write("```\n\n")
        for r in rows:
            f.write("## eps = %s\n\n```text\n" % r["label"])
            f.write("eps                       = %s  (exact decimal %s)\n"
                    % (r["label"], r["eps_exact"]))
            f.write("eps_double_bits           = 0x%016x  (eps_d = %s)\n"
                    % (r["eps_bits"], r["eps_d"].hex()))
            f.write("one_minus_eps_double_bits = 0x%016x  (1-eps_d = %s)\n"
                    % (r["ome_bits"], r["ome_d"].hex()))
            f.write("W_eps                     = 0x%016x  (%d)\n" % (r["W"], r["W"]))
            f.write("2*W_eps                   = 0x%016x  (%d)\n"
                    % (2 * r["W"], 2 * r["W"]))
            f.write("```\n\nConstraints: `0 <= X0 < 2^64` ok, `0 <= D64 < 2^64` ok, "
                    "`0 < 2*W_eps < 2^64` ok.\n\n")
    print("wrote", hpp)
    print("wrote", md)


if __name__ == "__main__":
    main()
